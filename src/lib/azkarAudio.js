const HOST = 'https://www.hisnmuslim.com/audio/ar/';

// mp3 URL for a dhikr item id, or null when no recorded audio is available.
export function azkarAudioUrl(dhikrId) {
  const aid = AZKAR_AUDIO_ID[dhikrId];
  return aid ? HOST + aid + '.mp3' : null;
}

// True if a recorded recitation exists for this dhikr id.
export function hasAzkarAudio(dhikrId) {
  return AZKAR_AUDIO_ID[dhikrId] != null;
}
